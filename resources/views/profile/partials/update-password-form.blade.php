@push('scripts')
<script src="https://cdn.jsdelivr.net/npm/sweetalert2@11"></script>
<script>
    document.addEventListener('DOMContentLoaded', function () {
        const passwordForm = document.querySelector('form[action="{{ route('password.update') }}"]');

        if (passwordForm) {
            passwordForm.addEventListener('submit', function (e) {
                e.preventDefault(); // Prevent default form submission

                Swal.fire({
                    title: 'Konfirmasi Perubahan Password',
                    text: "Anda yakin ingin menyimpan perubahan password?",
                    icon: 'warning',
                    showCancelButton: true,
                    confirmButtonColor: '#3085d6',
                    cancelButtonColor: '#d33',
                    confirmButtonText: 'Ya, Simpan!',
                    cancelButtonText: 'Batal'
                }).then((result) => {
                    if (result.isConfirmed) {
                        passwordForm.submit(); // Submit the form if confirmed
                    }
                });
            });
        }
    });
</script>
@endpush
